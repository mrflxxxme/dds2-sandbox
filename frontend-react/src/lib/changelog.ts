/**
 * Лента обновлений DDS — статический реестр.
 *
 * Как добавить новость: новая запись В НАЧАЛО массива, в том же PR, что и сама фича.
 * `id` менять нельзя — по нему считается «прочитано» (localStorage: dds_changelog_last_seen).
 * `date` — YYYY-MM-DD, дата выката на прод.
 */

export type ChangelogKind = 'feature' | 'fix' | 'improvement';

export interface ChangelogEntry {
    /** Стабильный уникальный ключ, ISO-дата + короткий слаг. Не переиспользовать. */
    id: string;
    /** Дата выката, YYYY-MM-DD. */
    date: string;
    kind: ChangelogKind;
    /** Раздел, которого касается новость (подпись как в сайдбаре). */
    section: string;
    /** Ссылка внутри проекта, без префикса /p/[slug]. Пустая строка — дашборд. */
    href: string;
    /** Заголовок — одна строка, без точки в конце. */
    title: string;
    /** Что изменилось. */
    summary: string;
    /** На что влияет — что пользователь теперь может или чего больше не увидит. */
    impact: string;
}

