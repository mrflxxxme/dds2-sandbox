/**
 * Подпись возраста данных у автообновления раздела FBS.
 *
 * Смысл теста — не арифметика, а читаемость: «обновлено 0 мин назад» человек
 * читает как поломку счётчика, поэтому свежие данные обязаны называться словами.
 */
import { describe, expect, it } from 'vitest';

import { formatAge } from '@/app/(main)/p/[slug]/warehouse/fbs/useAutoRefresh';

describe('formatAge', () => {
    it('данных ещё не было — подписи нет вовсе, а не «null»', () => {
        expect(formatAge(null)).toBe('');
    });

    it('свежее минуты — «только что», а не «0 мин назад»', () => {
        expect(formatAge(0)).toBe('только что');
        expect(formatAge(59_000)).toBe('только что');
    });

    it('минуты считаются вниз: 119 c — это ещё одна минута', () => {
        expect(formatAge(60_000)).toBe('1 мин назад');
        expect(formatAge(119_000)).toBe('1 мин назад');
        expect(formatAge(180_000)).toBe('3 мин назад');
    });

    it('после часа переходим на часы — «60 мин назад» нечитаемо', () => {
        expect(formatAge(59 * 60_000)).toBe('59 мин назад');
        expect(formatAge(60 * 60_000)).toBe('1 ч назад');
        expect(formatAge(150 * 60_000)).toBe('2 ч назад');
    });

    it('отрицательный возраст (часы клиента убежали вперёд) не даёт «-1 мин»', () => {
        expect(formatAge(-5_000)).toBe('только что');
    });
});
