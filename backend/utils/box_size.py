"""Канонизация строки размера коробки (box_size).

Пользователь вводит размер с разных раскладок/символов: латинская «x», русская
«х» (U+0445), знак умножения «×» (U+00D7), звёздочка. Визуально они одинаковы,
но как строки — разные, из-за чего «60x40x50» и «60х40х50» считались разными
коробками (баг на наполнении машины V-0027, баркод 2049985828474: ФЗ отдал
латиницу, а box_size_override сохранился кириллицей). Приводим все разделители к
латинской строчной «x».
"""

# Все варианты разделителя размеров → латинская строчная «x».
_BOX_SIZE_SEPARATORS = ("×", "*", ",", "/", "\\", "х", "Х", "X")


def normalize_box_size(value: str | None) -> str | None:
    """'60х40х50'/'60×40×50'/'60X40X50' → '60x40x50'. None/пусто → None."""
    if not value:
        return None
    s = value.strip()
    if not s:
        return None
    for ch in _BOX_SIZE_SEPARATORS:
        s = s.replace(ch, "x")
    return s
