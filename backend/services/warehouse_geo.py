def find_nearest_warehouse_by_city(
    city: str,
    open_warehouses: list[str],
) -> Optional[str]:
    """Find nearest open WB warehouse for the given delivery city.

    Uses CITY_COORDS for precise city-level geo matching.

    Args:
        city: city name from WB order feed
        open_warehouses: list of warehouse names that accept goods

    Returns:
        Name of the nearest open warehouse, or None if city unknown
    """
    city_coord = CITY_COORDS.get(city)
    if not city_coord:
        return None

    best_wh = None
    best_dist = float("inf")

    for wh_name in open_warehouses:
        wh_coord = WAREHOUSE_COORDS.get(wh_name)
        if not wh_coord:
            continue
        dist = haversine(city_coord[0], city_coord[1], wh_coord[0], wh_coord[1])
        if dist < best_dist:
            best_dist = dist
            best_wh = wh_name

    return best_wh

