def haversine(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Distance in km between two points on Earth."""
    R = 6371.0
    dlat = math.radians(lat2 - lat1)
    dlon = math.radians(lon2 - lon1)
    a = (
        math.sin(dlat / 2) ** 2
        + math.cos(math.radians(lat1))
        * math.cos(math.radians(lat2))
        * math.sin(dlon / 2) ** 2
    )
    return R * 2 * math.atan2(math.sqrt(a), math.sqrt(1 - a))


def find_nearest_warehouse(
    region_name: str,
    open_warehouses: list[str],
) -> Optional[str]:
    """Find nearest open WB warehouse for the given buyer region.

    Args:
        region_name: regionName from WB order (buyer's region)
        open_warehouses: list of warehouse names that accept goods

    Returns:
        Name of the nearest open warehouse, or None if region unknown
    """
    region_coord = REGION_COORDS.get(region_name)
    if not region_coord:
        return None

    best_wh = None
    best_dist = float("inf")

    for wh_name in open_warehouses:
        wh_coord = WAREHOUSE_COORDS.get(wh_name)
        if not wh_coord:
            continue
        dist = haversine(region_coord[0], region_coord[1], wh_coord[0], wh_coord[1])
        if dist < best_dist:
            best_dist = dist
            best_wh = wh_name

    return best_wh


