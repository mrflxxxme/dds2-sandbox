def _norm(s: str) -> str:
    return s.lower().replace("ё", "е")


# Паттерны, отсортированы по длине убыв. (tie-break при равной правой границе).
_COLOR_PATTERNS: list[tuple[str, str]] = sorted(
    {(_norm(alias), canon) for alias, canon in _COLOR_ALIASES.items()},
    key=lambda p: -len(p[0]),
)


def parse_color(article: str | None) -> str | None:
    """Цвет из артикула (каноничная форма) или None.

    Берём самое ПРАВОЕ вхождение (цвет обычно последний токен), при равной правой
    границе — самое ДЛИННОЕ (чтобы «темно-серый» бил вложенный «серый»). Substring-
    матч ловит слепленные с узором случаи: «кроликбежевый» → «бежевый».
    """
    if not article:
        return None
    s = _norm(article)
    best_end = -1
    best_len = -1
    best_canon: str | None = None
    for pattern, canon in _COLOR_PATTERNS:
        idx = s.rfind(pattern)
        if idx < 0:
            continue
        end = idx + len(pattern)
        if end > best_end or (end == best_end and len(pattern) > best_len):
            best_end = end
            best_len = len(pattern)
            best_canon = canon
    return best_canon
