"""
Парсер признаков товара из артикула продавца (vendor_code / article_seller).

Размер и цвет у многих категорий (ковры, шторы, покрывала, коврики, пледы…)
зашиты прямо в артикул: «200x300_бежевый», «BLACKOUT_150х240_кофейный»,
«ELKA_160х200/50*70/молочный». Модуль вытаскивает их БЕЗ обращения к WB API и без
отдельных колонок в БД — парсит ту же строку, что уже лежит в
`WbFunnelDaily.vendor_code`.

Покрытие по тканевым категориям (замерено на выгрузке номенклатуры default):
размер 90–100%, цвет 85–99%. Словарь цветов `_COLOR_ALIASES` — «ручка» точности,
пополняется при появлении новых цветов в карточках WB.
"""

import re

# Размер: NNN[xх*]NNN — латинская x, кириллическая х, звёздочка-разделитель.
# Берём ПЕРВОЕ совпадение: у ковров размер в начале артикула; у ковриков для
# ванной два размера (изделие_коврик) — первое = размер изделия.
_SIZE_RE = re.compile(r"(\d{2,4})\s*[xх*]\s*(\d{2,4})", re.IGNORECASE)


def parse_size(article: str | None) -> str | None:
    """Размер из артикула в нормальном виде «200x300» (латинская x) или None."""
    if not article:
        return None
    m = _SIZE_RE.search(article)
    if not m:
        return None
    return f"{m.group(1)}x{m.group(2)}"


