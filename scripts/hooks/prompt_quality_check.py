#!/usr/bin/env python3
"""UserPromptSubmit hook — детектор расплывчатого ТЗ (2026-07-02).

Ловит промпты, по которым агент вынужден угадывать (баг без указателя,
«ничего не изменилось» без данных об окружении, «переделай дизайн» без
референса), и через stdout инжектит агенту инструкцию: СНАЧАЛА задать
1-3 уточняющих вопроса, ПОТОМ работать. Хорошо поставленные промпты
(URL/порт, путь к файлу, ID сущности, детальное ТЗ) пропускает молча.

Статистика месяца, по которой калиброван: 50-70 багов без указателя,
~10 «ничего не изменилось» (половина — кэш/не тот порт, а не код),
портал ФФ переделан 3 раза из-за «сделай красиво» без референса.
"""
import json
import re
import sys


def main() -> int:
    try:
        payload = json.load(sys.stdin)
    except Exception:
        return 0
    prompt = (payload.get("prompt") or "").strip()
    if not prompt:
        return 0
    low = prompt.lower()

    # ── Пропуск: команды, короткие подтверждения, ответы на вопросы агента ──
    if low.startswith("/") or len(low) < 14:
        return 0
    # Есть указатель → промпт самодостаточен, молчим.
    has_pointer = bool(
        re.search(r"https?://|localhost|:\d{4}\b", low)
        or re.search(r"[\w-]+\.(py|tsx?|md|sql|json|ya?ml)\b", low)
        or re.search(r"\b(backend|frontend-react|migrations|scripts)/", low)
        or re.search(r"/p/[\w-]+/", low)
        or re.search(r"\b\d{5,}\b", low)  # ID поставки/заявки/nm_id
        or re.search(r"\basm[- ]?\d+", low)
        or re.search(r"[a-zа-яё0-9]+_[a-zа-яё0-9]", low)  # артикул: швабра_ep-200, 200x300_бежевый
        or re.search(r"\b[a-z]{2,}-[a-z0-9]{3,}\b", low)  # код: bz-yy8820a, ep-200
        or "@" in prompt
    )
    # Детальное ТЗ (длинное, со структурой) — не трогаем даже без указателя.
    detailed = len(prompt) > 500 or bool(re.search(r"(^|\s)\d\.\s", prompt))

    # Мета-обсуждение процесса/промптов/сетапа — это НЕ баг-репорт, молчим.
    # Ловит ложные позитивы, где слово-триггер («неправильно», «баг») относится
    # к разговору о методе, а не к сломанной фиче: «неправильно пишу промт»,
    # «как решать такие баги», «что это даст», «подкрути хук/гейт/скил».
    is_meta = bool(
        re.search(
            r"промпт|промт|\bтз\b|как (я |мне )?(правильно|лучше|стоит|решать|писать|"
            r"задавать|формулир|подходить)|что (это )?даст|методолог|\bподход\b|"
            r"воркфлоу|workflow|объясни|посоветуй|как думаешь|стоит ли|имеет ли смысл|"
            r"\bскил\w*|\bhook\b|\bхук\w*|\bгейт\w*|процесс разработ|"
            r"задач[аи].{0,25}(час|минут)|решается за (минут|секунд)|"  # обобщение про длительность работы
            r"(несколько|за) час[ао]в",
            low,
        )
    )

    hints: list[str] = []

    # ── «Ничего не изменилось» — сперва окружение, потом дебаг ──
    # (молчим, если юзер уже дал данные об окружении: рефреш/порт/кэш)
    if re.search(r"ничего не измен|не изменил[оа]сь|вс[её] так ?же|опять так ?же", low) and not re.search(
        r"рефреш|обновил|кэш|порт|localhost|:\d{4}\b", low
    ):
        hints.append(
            "Промпт класса «ничего не изменилось». ПЕРЕД повторным дебагом кода задай "
            "вопросы об окружении (AskUserQuestion): жёсткий рефреш был? какой порт/стек "
            "(3000/3001/3002)? тот же черновик/сущность? Половина таких случаев в этом "
            "проекте — turbopack-кэш или не тот инстанс, а не код."
        )
    # ── Баг-репорт без указателя ──
    elif not has_pointer and not detailed and not is_meta and re.search(
        r"не работает|ошибк|\bбаг\b|слома|упал[оа]?\b|падает|неправильно|не сходится|"
        r"не отображ|не показыва|выдает|выдаёт|пуст(ые|о|ая)|вылет|глючит|зависает|дубл[иь]",
        low,
    ):
        hints.append(
            "Похоже на баг-репорт БЕЗ указателя (нет URL/порта, файла, ID сущности). "
            "НЕ начинай анализ вслепую: сначала задай 1-3 конкретных вопроса через "
            "AskUserQuestion — URL с портом? какое действие? что видит и что ожидал? "
            "проверял ли руками (эталон)? Если место однозначно следует из контекста "
            "текущей сессии — работай сразу, вопросы не нужны."
        )
    # ── Дизайн без референса ──
    elif not is_meta and re.search(r"дизайн|некрасив|ужасн|уродлив|красив|современн", low) and not re.search(
        r"референс|как (на|в) |как у ", low
    ) and re.search(r"передела|исправ|сдела|поправ|поработай", low):
        hints.append(
            "Правка дизайна без референса и критерия. Перед работой уточни через "
            "AskUserQuestion: какая страница-референс из нашего приложения? что именно "
            "не так (раскладка/цвета/плотность)? десктоп или мобилка? Иначе высок риск "
            "переделывать несколько раз (прецедент: портал ФФ переделан 3 раза)."
        )

    if hints:
        hints.append(
            "Подскажи юзеру (одной строкой в конце ответа) формулу промпта: "
            "ЧТО · ГДЕ (URL/файл/ID) · КАК ПОЙМЁМ, ЧТО ГОТОВО — подробнее docs/PROMPT_GUIDE.md."
        )
        print("[ТЗ-ГЕЙТ] " + " ".join(hints))
    return 0


if __name__ == "__main__":
    sys.exit(main())
